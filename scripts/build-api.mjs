// Compiles the Express API (TypeScript with .ts import specifiers) into one plain ES module for Vercel.
// npm packages stay external (Vercel installs them from package.json); only our own source is bundled.
// Run `npm run build:api` after changing anything under apps/api or packages/core, then commit api/_app.js.
import {build} from 'esbuild';
await build({
  entryPoints:['apps/api/src/vercel-entry.ts'],
  outfile:'api/_app.js',
  bundle:true,platform:'node',format:'esm',target:'node22',
  packages:'external',legalComments:'none',logLevel:'warning',
  banner:{js:'// GENERATED by scripts/build-api.mjs from apps/api and packages/core. Do not edit; run `npm run build:api`.'}
});
console.log('Built api/_app.js');
